using System.Text.RegularExpressions;

namespace Chummer.Run.Api.Services;

public static partial class PublicFacingCopyHumanizer
{
    private static readonly (string From, string To)[] Replacements =
    [
        ("generated by AI", "created"),
        ("AI-generated", "created"),
        ("AI generated", "created"),
        ("Unmixr AI", "Unmixr"),
        ("ALICE", "Alice"),
        ("Black Ledger", "campaign city"),
        ("source packet", "source"),
        ("source-backed", "checked"),
        ("source-aware", "checked"),
        ("first-party", "Chummer"),
        ("microproof", "note"),
        ("proof receipts", "checks"),
        ("proof receipt", "check"),
        ("proof shelf", "checks"),
        ("proof", "check"),
        ("receipts", "records"),
        ("receipt", "record"),
        ("operator view", "account view"),
        ("operator-facing", "private"),
        ("operator", "user"),
        ("grounded", "current"),
        ("governed", "reviewed"),
        ("canonical", "current"),
        ("handoff", "next step"),
        ("starter lane", "starter path"),
        ("world lanes", "campaign extras"),
        ("lanes", "paths"),
        ("lane", "path"),
        ("rails", "paths"),
        ("rail", "path"),
        ("generated", "created"),
    ];

    public static string Clean(string? value)
    {
        if (string.IsNullOrWhiteSpace(value))
        {
            return string.Empty;
        }

        string cleaned = value.Trim();
        foreach ((string from, string to) in Replacements)
        {
            cleaned = cleaned.Replace(from, to, StringComparison.OrdinalIgnoreCase);
        }

        cleaned = StandaloneAiRegex().Replace(cleaned, "assistant");
        cleaned = DuplicateWhitespaceRegex().Replace(cleaned, " ");
        cleaned = SpaceBeforePunctuationRegex().Replace(cleaned, "$1");
        return cleaned.Trim();
    }

    public static IReadOnlyList<string> CleanLines(IEnumerable<string>? values)
        => values?
            .Select(Clean)
            .Where(static value => !string.IsNullOrWhiteSpace(value))
            .ToArray()
           ?? Array.Empty<string>();

    [GeneratedRegex(@"\bAI\b", RegexOptions.CultureInvariant)]
    private static partial Regex StandaloneAiRegex();

    [GeneratedRegex(@"\s+", RegexOptions.CultureInvariant)]
    private static partial Regex DuplicateWhitespaceRegex();

    [GeneratedRegex(@"\s+([.,;:!?])", RegexOptions.CultureInvariant)]
    private static partial Regex SpaceBeforePunctuationRegex();
}
