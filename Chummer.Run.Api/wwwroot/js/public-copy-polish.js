(function () {
  const SHOW_TEXT = true;
  if (!SHOW_TEXT || typeof document === "undefined") {
    return;
  }

  const replacements = [
    [/\bgenerated by AI\b/gi, "created"],
    [/\bAI-generated\b/gi, "created"],
    [/\bAI generated\b/gi, "created"],
    [/\bAI\b/g, "helper"],
    [/\bBlack Ledger\b/g, "campaign city"],
    [/\bproof receipts\b/gi, "checks"],
    [/\bproof receipt\b/gi, "check"],
    [/\bproof\b/gi, "check"],
    [/\breceipts\b/gi, "records"],
    [/\breceipt\b/gi, "record"],
    [/\bproviders\b/gi, "services"],
    [/\bprovider\b/gi, "service"],
    [/\boperator lane\b/gi, "user path"],
    [/\boperator\b/gi, "user"],
    [/\bsource packet\b/gi, "source"],
  ];

  const blockedTags = new Set([
    "CODE",
    "PRE",
    "SCRIPT",
    "STYLE",
    "TEXTAREA",
    "INPUT",
    "SELECT",
    "OPTION",
  ]);

  function shouldSkip(node) {
    for (let element = node.parentElement; element; element = element.parentElement) {
      const tagName = element.tagName;
      if (tagName === "CODE" || tagName === "PRE" || blockedTags.has(tagName) || element.hasAttribute("data-no-humanize")) {
        return true;
      }
    }

    return false;
  }

  function cleanText(value) {
    let next = value;
    for (const [pattern, replacement] of replacements) {
      next = next.replace(pattern, replacement);
    }

    return next.replace(/\s+([.,;:!?])/g, "$1");
  }

  function run() {
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
    const nodes = [];
    for (let node = walker.nextNode(); node; node = walker.nextNode()) {
      if (!shouldSkip(node)) {
        nodes.push(node);
      }
    }

    for (const node of nodes) {
      const cleaned = cleanText(node.nodeValue || "");
      if (cleaned !== node.nodeValue) {
        node.nodeValue = cleaned;
      }
    }
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", run, { once: true });
    return;
  }

  run();
})();
