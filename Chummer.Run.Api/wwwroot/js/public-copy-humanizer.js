(function () {
  "use strict";

  var replacements = [
    [/\bALICE\b/g, "Alice"],
    [/\bBlack Ledger\b/gi, "campaign city"],
    [/\bproof receipt\b/gi, "check"],
    [/\bgenerated by AI\b/gi, "created"],
    [/\bAI-generated\b/gi, "created"],
    [/\bAI generated\b/gi, "created"],
    [/\bgenerated\b/gi, "created"],
    [/\ban\s+AI\b/gi, "a"],
    [/\bAI\b/g, "help"],
    [/\bUnmixr AI\b/g, "Unmixr"],
    [/\bsource packet\b/gi, "source"],
    [/\bprovider\b/gi, "service"],
    [/\bLTD\b/g, "tool"],
    [/\bproof trail\b/gi, "checks"],
    [/\bproof\b/gi, "check"],
    [/\breceipt\b/gi, "check"],
    [/\boperator lane\b/gi, "user path"],
    [/\boperator view\b/gi, "account view"],
    [/\boperator-facing\b/gi, "private"],
    [/\bstarter lane\b/gi, "starter path"],
    [/\s+([.,;:!?])/g, "$1"],
    [/[ \t]{2,}/g, " "]
  ];

  function cleanText(value) {
    var cleaned = value;
    for (var i = 0; i < replacements.length; i += 1) {
      cleaned = cleaned.replace(replacements[i][0], replacements[i][1]);
    }

    return cleaned;
  }

  function shouldSkip(node) {
    if (!node || !node.parentElement) {
      return true;
    }

    var tagName = node.parentElement.tagName;
    return tagName === "SCRIPT" || tagName === "STYLE" || tagName === "TEXTAREA" || tagName === "CODE" || tagName === "PRE";
  }

  function polish(root) {
    if (!root || !document.createTreeWalker) {
      return;
    }

    var walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
      acceptNode: function (node) {
        return shouldSkip(node) ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT;
      }
    });
    var nodes = [];
    var node;
    while ((node = walker.nextNode())) {
      nodes.push(node);
    }

    nodes.forEach(function (textNode) {
      var next = cleanText(textNode.nodeValue);
      if (next !== textNode.nodeValue) {
        textNode.nodeValue = next;
      }
    });
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", function () {
      polish(document.body);
    });
  } else {
    polish(document.body);
  }
})();
